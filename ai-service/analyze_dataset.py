"""Stage 1: inspect, merge and clean the two ClinicFlow CSV files.

Run from the ai-service/ folder:   python analyze_dataset.py

Outputs
  dataset/clinicflow_cleaned.csv   merged + cleaned rows with a `group` column
  reports/dataset_report.md        numbers behind the dataset analysis
  reports/class_distribution.png

Why merge? The train file has 10 specialties and the validation file has 5,
four of which (ENT, Ophthalmology, Oncology, Rheumatology) are absent from
train. Using the files as given would test on classes the model never saw.
We merge them and create our own group-aware split instead.
"""
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns
from scipy.sparse.csgraph import connected_components
from sklearn.feature_extraction.text import TfidfVectorizer

from app.text_utils import clean_text

ROOT = Path(__file__).parent
TRAIN = ROOT / "dataset" / "clinicflow_train.csv"
VAL = ROOT / "dataset" / "clinicflow_validation.csv"
OUT_CSV = ROOT / "dataset" / "clinicflow_cleaned.csv"
REPORTS = ROOT / "reports"
REPORTS.mkdir(exist_ok=True)

# Rows whose cleaned text is at least this similar are treated as paraphrases
# of one scenario and are always kept on the same side of any split.
GROUP_SIMILARITY = 0.6

# Columns written AFTER the specialty was decided; never usable as inputs.
LEAKY_COLUMNS = ["urgency_level", "confidence_score", "critical_questions",
                 "possible_conditions", "reasoning"]


def describe(name: str, df: pd.DataFrame, lines: list) -> None:
    lines.append(f"## {name}\n")
    lines.append(f"- Rows x columns: {df.shape[0]} x {df.shape[1]}")
    lines.append(f"- Missing values (total): {int(df.isna().sum().sum())}")
    lines.append(f"- Exact duplicate rows (ignoring id): {int(df.drop(columns=['id']).duplicated().sum())}")
    lines.append(f"- Repeated symptom_description: {int(df.symptom_description.duplicated().sum())}")
    lines.append(f"- Labels: {sorted(df.primary_specialty.unique())}")
    counts = df.primary_specialty.value_counts()
    lines.append("\nClass distribution:\n")
    lines.append("| specialty | rows |\n|---|---|")
    lines += [f"| {k} | {v} |" for k, v in counts.items()]
    lines.append("")


def main() -> None:
    train = pd.read_csv(TRAIN)
    val = pd.read_csv(VAL)
    lines = ["# Dataset report (generated by analyze_dataset.py)\n"]
    describe("clinicflow_train.csv", train, lines)
    describe("clinicflow_validation.csv", val, lines)

    only_val = sorted(set(val.primary_specialty) - set(train.primary_specialty))
    lines.append(f"Labels only in validation: {only_val}\n")

    train["source_file"], val["source_file"] = "train", "validation"
    df = pd.concat([train, val], ignore_index=True)

    # --- label consistency -------------------------------------------------
    df["primary_specialty"] = df["primary_specialty"].astype(str).str.strip()
    lines.append("## Merged data\n")
    lines.append(f"- Rows before cleaning: {len(df)}")

    # --- exact duplicate text ---------------------------------------------
    df["text_clean"] = df["symptom_description"].map(clean_text)
    conflict = df.groupby("text_clean").primary_specialty.nunique()
    n_conflict = int((conflict > 1).sum())
    lines.append(f"- Identical texts with CONFLICTING labels: {n_conflict}")
    before = len(df)
    df = df.drop_duplicates(subset="text_clean", keep="first").reset_index(drop=True)
    lines.append(f"- Dropped duplicate texts: {before - len(df)}  -> rows now {len(df)}")

    # --- empty / very short text ------------------------------------------
    df = df[df.text_clean.str.split().str.len() >= 3].reset_index(drop=True)
    lines.append(f"- Rows after removing <3-word texts: {len(df)}")

    # --- near-duplicate grouping (prevents leakage) ------------------------
    vec = TfidfVectorizer(stop_words="english").fit(df.text_clean)
    X = vec.transform(df.text_clean)
    sim = (X @ X.T).toarray()
    np.fill_diagonal(sim, 0)
    n_groups, group = connected_components(sim > GROUP_SIMILARITY)
    df["group"] = group
    nn = sim.max(axis=1)
    lines.append(f"- Median nearest-neighbour cosine similarity: {np.median(nn):.2f}")
    lines.append(f"- Share of rows with a near-twin (cosine > 0.8): {(nn > 0.8).mean():.1%}")
    lines.append(f"- Near-duplicate groups at threshold {GROUP_SIMILARITY}: {n_groups} "
                 f"(i.e. ~{n_groups} distinct scenarios in {len(df)} rows)")

    # groups that span more than one label are a label-consistency warning
    multi = df.groupby("group").primary_specialty.nunique()
    lines.append(f"- Groups containing more than one specialty label: {int((multi > 1).sum())}")
    if (multi > 1).any():
        mix = (df[df.group.isin(multi[multi > 1].index)]
               .groupby("group").primary_specialty.unique())
        lines.append("  - Mixed groups (label sets): "
                     + "; ".join(sorted({" / ".join(sorted(v)) for v in mix})))

    # --- final class distribution -----------------------------------------
    counts = df.primary_specialty.value_counts()
    lines.append("\nFinal class distribution (cleaned):\n")
    lines.append("| specialty | rows | groups |\n|---|---|---|")
    for k, v in counts.items():
        lines.append(f"| {k} | {v} | {df[df.primary_specialty == k].group.nunique()} |")

    lines.append("\n## Limitations\n")
    lines += [
        "- Provenance and licence of the CSVs are NOT documented; the text looks synthetic (uniform style).",
        "- Long, clean, first-person narratives (~59 words). Real users type short, informal text.",
        "- Roughly one-third of rows are paraphrases of the same scenario, so scores on a random split are inflated.",
        f"- Leaky columns excluded from model inputs: {', '.join(LEAKY_COLUMNS)}.",
        "- Endocrinology has very few distinct scenarios; ENT/Ophthalmology/Oncology/Rheumatology come only from the validation file.",
        "- Not clinically validated. Output is a broad specialty suggestion, never a diagnosis.",
    ]

    out = df[["id", "source_file", "symptom_description", "text_clean",
              "primary_specialty", "group"]]
    out.to_csv(OUT_CSV, index=False)
    (REPORTS / "dataset_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    plt.figure(figsize=(8, 5))
    sns.barplot(x=counts.values, y=counts.index, color="#2a6f97")
    plt.xlabel("rows"); plt.ylabel("")
    plt.title("Class distribution after merging and cleaning")
    plt.tight_layout()
    plt.savefig(REPORTS / "class_distribution.png", dpi=150)
    print("\n".join(lines))
    print(f"\nWrote {OUT_CSV} and reports/dataset_report.md")


if __name__ == "__main__":
    main()
